const STEP = 6; // 字宽 5 + 1 列间隔

const textWidth = (text, scale = 1) => String(text).length * STEP * scale;

// cv 只需提供 set(x, y, color)。
function drawText(cv, x, y, text, color, scale = 1) {
  let cx = x;
  for (const raw of String(text).toUpperCase()) {
    const g = GLYPHS[raw];
    if (g) {
      for (let r = 0; r < 7; r++) {
        const row = g[r];
        for (let c = 0; c < 5; c++) {
          if (row[c] !== '1') continue;
          for (let dy = 0; dy < scale; dy++) {
            for (let dx = 0; dx < scale; dx++) {
              cv.set(cx + c * scale + dx, y + r * scale + dy, color);
            }
          }
        }
      }
    }
    cx += STEP * scale;
  }
  return cx - x;
}

